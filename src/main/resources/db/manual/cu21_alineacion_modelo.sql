-- Migracion manual del modelo requerido por el CU-21.
-- Ejecutar solo luego de revisar y respaldar la base.

BEGIN;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM pregunta
        WHERE length(btrim(nombre)) > 100
           OR length(btrim(pregunta)) > 150
           OR (descripcion IS NOT NULL AND length(btrim(descripcion)) > 500)
    ) THEN
        RAISE EXCEPTION
            'Existen literales que exceden las nuevas longitudes del CU-21';
    END IF;

    IF EXISTS (
        SELECT codigo_factor, upper(btrim(nombre)), count(*)
        FROM pregunta
        WHERE eliminado = false
        GROUP BY codigo_factor, upper(btrim(nombre))
        HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION
            'Existen preguntas activas duplicadas por nombre normalizado';
    END IF;

    IF EXISTS (
        SELECT codigo_factor, upper(btrim(pregunta)), count(*)
        FROM pregunta
        WHERE eliminado = false
        GROUP BY codigo_factor, upper(btrim(pregunta))
        HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION
            'Existen preguntas activas duplicadas por texto normalizado';
    END IF;
END
$$;

UPDATE pregunta
SET nombre = upper(btrim(nombre)),
    pregunta = upper(btrim(pregunta)),
    descripcion = CASE
        WHEN descripcion IS NULL THEN NULL
        ELSE upper(btrim(descripcion))
    END;

ALTER TABLE pregunta
    ALTER COLUMN nombre TYPE varchar(100),
    ALTER COLUMN pregunta TYPE varchar(150),
    ALTER COLUMN descripcion TYPE varchar(500);

ALTER TABLE ponderacion_item
    ALTER COLUMN ponderacion TYPE numeric(38,2)
    USING ponderacion::numeric(38,2);

ALTER TABLE caracteristica_puesto
    ALTER COLUMN ponderacion_minima TYPE numeric(38,2)
    USING ponderacion_minima::numeric(38,2);

ALTER TABLE resultado_competencia
    ALTER COLUMN puntaje_obtenido TYPE numeric(38,2)
    USING puntaje_obtenido::numeric(38,2);

ALTER TABLE cuestionario
    ALTER COLUMN puntaje_final TYPE numeric(38,2)
    USING puntaje_final::numeric(38,2);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'pregunta'
          AND column_name = 'codigo'
          AND is_identity = 'YES'
    ) THEN
        ALTER TABLE pregunta
            ALTER COLUMN codigo ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END
$$;

DO $$
DECLARE
    secuencia text;
    ultimo_codigo bigint;
BEGIN
    secuencia := pg_get_serial_sequence('public.pregunta', 'codigo');

    IF secuencia IS NOT NULL THEN
        SELECT coalesce(max(codigo), 0)
        INTO ultimo_codigo
        FROM pregunta;

        IF ultimo_codigo > 0 THEN
            PERFORM setval(secuencia::regclass, ultimo_codigo, true);
        ELSE
            PERFORM setval(secuencia::regclass, 1, false);
        END IF;
    END IF;
END
$$;

ALTER TABLE pregunta
    DROP CONSTRAINT IF EXISTS uk_pregunta_factor_nombre,
    DROP CONSTRAINT IF EXISTS uk_pregunta_factor_texto;

DROP INDEX IF EXISTS uk_pregunta_factor_nombre;
DROP INDEX IF EXISTS uk_pregunta_factor_texto;
DROP INDEX IF EXISTS uk_pregunta_activa_factor_nombre;
DROP INDEX IF EXISTS uk_pregunta_activa_factor_texto;

CREATE UNIQUE INDEX uk_pregunta_activa_factor_nombre
    ON pregunta (codigo_factor, upper(btrim(nombre)))
    WHERE eliminado = false;

CREATE UNIQUE INDEX uk_pregunta_activa_factor_texto
    ON pregunta (codigo_factor, upper(btrim(pregunta)))
    WHERE eliminado = false;

ALTER TABLE ponderacion_item
    DROP CONSTRAINT IF EXISTS ck_ponderacion_item_no_negativa,
    DROP CONSTRAINT IF EXISTS ck_ponderacion_item_dos_decimales;

ALTER TABLE ponderacion_item
    ADD CONSTRAINT ck_ponderacion_item_no_negativa
        CHECK (ponderacion >= 0),
    ADD CONSTRAINT ck_ponderacion_item_dos_decimales
        CHECK (scale(ponderacion) = 2);

COMMIT;
